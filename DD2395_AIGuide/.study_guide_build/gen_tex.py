#!/usr/bin/env python3
"""Generate study_guide.tex from scheme JSONs + cluster.json."""
import json, re, os

BASE = '/home/yunshan/Documents/KTHAnteckningar/DD2395_AIGuide/.study_guide_build'
OUT = '/home/yunshan/Documents/KTHAnteckningar/DD2395_AIGuide/study_guide.tex'

PREAMBLE = r"""\documentclass[12pt, a4paper]{article}

% Essential packages for math and formatting
\usepackage{amsmath, amssymb, amsthm}
\usepackage{geometry}
\geometry{margin=1in}
\usepackage{enumitem}
\usepackage{xcolor}

% Package for creating clean "Scheme" boxes
\usepackage{tcolorbox}
\tcbuselibrary{skins, breakable}

% Define a custom box for Solution Schemes
\newtcolorbox{schemebox}[1]{
    colback=blue!3!white,
    colframe=blue!75!black,
    fonttitle=\bfseries,
    title=Algorithm: #1,
    boxrule=1pt,
    arc=4pt,
    breakable
}

% Define a custom box for Exam Variations/Traps
\newtcolorbox{trapbox}{
    colback=red!3!white,
    colframe=red!75!black,
    fonttitle=\bfseries,
    title=Exam Variations \& Traps,
    boxrule=1pt,
    arc=4pt,
    breakable
}

\begin{document}

\title{Exam Solution Schemes \& Study Guide}
\author{Generated by AI}
\date{\today}
\maketitle
\tableofcontents
\newpage
"""

UNICODE_MAP = {
    '—': '---', '–': '--',
    '⊑': '$\\sqsubseteq$', '⊆': '$\\subseteq$', '⊇': '$\\supseteq$',
    '≤': '$\\leq$', '≥': '$\\geq$', '≠': '$\\neq$',
    '×': '$\\times$', '⊕': '$\\oplus$', '→': '$\\rightarrow$',
    '‘': "'", '’': "'", '“': '``', '”': "''",
}

def sanitize(s):
    # unicode replacements first
    for k, v in UNICODE_MAP.items():
        s = s.replace(k, v)
    # split into math ($...$) and non-math segments
    parts = re.split(r'(\$[^$]*\$)', s)
    out = []
    for p in parts:
        if p.startswith('$') and p.endswith('$') and len(p) >= 2:
            out.append(p)
            continue
        p = p.replace('\\n', '\\textbackslash n')  # literal backslash-n (printf)
        p = p.replace('\\0', '\\textbackslash 0')  # literal NUL char '\0'
        p = p.replace('%', '\\%').replace('&', '\\&').replace('#', '\\#')
        p = p.replace('_', '\\_')
        p = p.replace('^', '\\textasciicircum{}')
        p = p.replace('<', '$<$').replace('>', '$>$')
        out.append(p)
    return ''.join(out)

def main():
    cluster = json.load(open(os.path.join(BASE, 'cluster.json')))
    qtypes = cluster['question_types']
    body = []
    for i, qt in enumerate(qtypes):
        sp = os.path.join(BASE, f'scheme_{i:02d}.json')
        if not os.path.exists(sp):
            body.append(f'% NOTE: scheme file missing for question type {i+1}: {qt["name"]}\n')
            continue
        try:
            sc = json.load(open(sp))
        except Exception as e:
            body.append(f'% NOTE: scheme file invalid for question type {i+1}: {e}\n')
            continue
        n = i + 1
        L = []
        L.append(f'\\section{{Question Type {n}: {sanitize(sc["name"])}}}\n')
        # How to Identify
        kws = sc['identify_keywords']
        kw_str = ', '.join(f"``{sanitize(k)}''" for k in kws)
        L.append('\\subsection*{How to Identify}')
        L.append(f'Use this scheme when the problem provides {sanitize(sc["identify_givens"])} and asks you to find/do the following: {sanitize(sc["identify_target"])} Look for keywords like: \\textit{{{kw_str}}}.\n')
        # schemebox
        L.append(f'\\begin{{schemebox}}{{{{{sanitize(sc["strategy_name"])}}}}}')
        L.append('\\begin{enumerate}[label=\\textbf{Step \\arabic*:}, leftmargin=*]')
        for st in sc['algorithm']:
            L.append(f'    \\item \\textbf{{{sanitize(st["action"])}:}} {sanitize(st["detail"])}')
        L.append('\\end{enumerate}')
        L.append('\\end{schemebox}\n')
        # trapbox
        L.append('\\begin{trapbox}')
        L.append('\\begin{itemize}')
        for j, v in enumerate(sc['variations'], 1):
            L.append(f'    \\item \\textbf{{Variation {j} ({sanitize(v["name"])}):}} {sanitize(v["detail"])}')
        L.append('\\end{itemize}')
        L.append('\\end{trapbox}\n')
        # worked example
        L.append('\\subsection*{Worked Example (Mapped to Scheme)}')
        L.append(f'\\textbf{{Problem:}} {sanitize(sc["example_problem"])}\n')
        L.append('\\textbf{Solution:}')
        L.append('\\begin{itemize}')
        for st in sc['example_steps']:
            L.append(f'    \\item \\textit{{Applying {sanitize(st["step_ref"])}:}} {sanitize(st["work"])}')
        L.append('\\end{itemize}')
        L.append(f'\\textit{{Source exam:}} {sanitize(sc["example_source"])}\n')
        body.append('\n'.join(L))

    # coverage note
    cov = ['\\section*{Coverage Note}', '\\begin{itemize}']
    short_names = [
        'Custom hash-function analysis', 'Cache/timing side channels',
        'Memory-safety exploits', 'Bell-LaPadula access control',
        'Protocol flaw analysis', 'Concept true/false',
        'Block-cipher mode analysis', 'Web attacks (XSS/CSRF/SQLi)',
        'Password storage analysis', 'DoS construction and countermeasures',
        'Social-engineering analysis',
    ]
    for i, qt in enumerate(qtypes):
        cov.append(f'    \\item \\textbf{{Question Type {i+1} ({short_names[i]}):}} appeared in approximately {qt["frequency"]} analyzed exam questions.')
    cov.append('\\end{itemize}')
    body.append('\n'.join(cov))

    tex = PREAMBLE + '\n' + '\n'.join(body) + '\n\\end{document}\n'
    with open(OUT, 'w') as f:
        f.write(tex)
    print('sections written:', sum(1 for i in range(len(qtypes)) if os.path.exists(os.path.join(BASE, f'scheme_{i:02d}.json'))))

if __name__ == '__main__':
    main()
